"""Immutable-cluster membership and hierarchy-level extraction.

This utility consumes ``total_data.csv`` and ``tree_splits.txt``
generated by fully immutable versions of ``reconstruct_hierarchy.cpp``
and ``run_clustering.cpp``. Every tree node has a permanent ID: root 0,
followed by two fresh child IDs per split. The hierarchy levels exposed
here are true tree depths below a selected node, not global
clustering-iteration numbers.

Requires Python 3.10 or later. Inputs and outputs follow the documented
working-directory contract; generated inputs require valid provenance.
"""

from __future__ import annotations

import sys
from dataclasses import dataclass
from pathlib import Path

import numpy as np
import pandas as pd

from pipeline_cli import Reask, ask, human_int, is_word, is_yes, prompt_input
from pipeline_formats import (
    TreeTopology,
    read_tree_states,
    read_tree_topology,
    render_cluster_list,
    validate_tree_states,
)
from pipeline_io import (
    TREE_STATES_FILE,
    TREE_TOPOLOGY_FILE,
    invalidate_dependents,
    provenance_path,
    publication_unchanged,
    verify_artifacts,
    write_provenance,
    write_text_atomically,
)

PATH_COLUMN = "0"


@dataclass(frozen=True)
class ClusterView:
    """Materialized information for one selected immutable tree node.

    Attributes:
        node_id: Selected immutable node ID.
        member_indices: Zero-based history rows belonging to the
            selected node.
        max_level: Maximum descendant edge depth; zero for a leaf.
        leaf_subclusters: Sorted terminal descendant node IDs.
    """

    node_id: int
    member_indices: np.ndarray
    max_level: int
    leaf_subclusters: tuple[int, ...]


