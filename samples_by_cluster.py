def _write_leaf_cluster_file(view: ClusterView) -> Path:
    """Write a selected node's terminal IDs with provenance.

    Args:
        view: Validated selected-node membership and terminal
            descendants.

    Returns:
        The committed ``cluster_<n>.txt`` path in the current directory.

    Raises:
        OSError: If output publication or hashing fails.
        ValueError: If input provenance is invalid.
    """
    cluster_filename = Path(f"cluster_{view.node_id}.txt")
    cluster_text = render_cluster_list(view.leaf_subclusters)
    record = {
        "stage": "cluster_export",
        "inputs": [Path(TREE_STATES_FILE), Path(TREE_TOPOLOGY_FILE)],
        "parents": [provenance_path(Path(TREE_STATES_FILE))],
        "producer": Path(__file__),
    }
    manifest = provenance_path(cluster_filename)
    # An identical export changes nothing, so it keeps its dependents.
    if publication_unchanged(manifest, {cluster_filename: cluster_text},
                             **record):
        return cluster_filename
    invalidate_dependents(
        [cluster_filename, manifest], [Path.cwd(), Path.cwd().parent],
    )
    write_text_atomically(cluster_filename, cluster_text)
    write_provenance(manifest, outputs=[cluster_filename], **record)
    return cluster_filename


def write_cluster_files(
    data: pd.DataFrame,
    topology: TreeTopology,
    view: ClusterView,
    level: int,
) -> None:
    """Write leaf-subcluster and hierarchy-level output files.

    Write immutable leaf-subcluster and hierarchy-level output files.

    ``cluster_<n>.txt`` contains the terminal descendant leaves of
    immutable node ``n``. ``cluster_<n>_hier_<level>.txt`` groups the
    selected node's samples by the tree frontier exactly ``level`` edges
    below that node.

    Args:
        data: Decoded immutable ``total_data.csv``.
        topology: Validated immutable tree topology.
        view: Selected-cluster information returned by
            ``build_cluster_view``.
        level: Tree depth below the selected node; level 1 is its
            immediate children.

    Raises:
        ValueError: If the requested level is invalid or the frontier
            does not partition the selected cluster exactly once.
    """
    if not 1 <= level <= view.max_level:
        raise ValueError(
            f"Hierarchy level should be between 1 and {view.max_level}."
        )

    cluster_filename = _write_leaf_cluster_file(view)
    hierarchy_filename = Path(
        f"cluster_{view.node_id}_hier_{level}.txt"
    )

    states = data.iloc[:, 1:].to_numpy(dtype=np.int64, copy=False)
    frontier = _frontier_at_level(topology, view.node_id, level)
    selected = view.member_indices
    assignment_count = np.zeros(len(selected), dtype=np.int8)
    grouped_indices: list[tuple[int, np.ndarray]] = []

    for frontier_node in frontier:
        creation_split = topology.creation_split[frontier_node]
        member_mask = states[selected, creation_split] == frontier_node
        local_indices = np.flatnonzero(member_mask)
        if local_indices.size == 0:
            raise ValueError(
                f"Hierarchy frontier node {frontier_node} at level {level} "
                f"contains no samples within cluster {view.node_id}."
            )
        assignment_count[local_indices] += 1
        grouped_indices.append((frontier_node, selected[local_indices]))

    bad_assignments = np.flatnonzero(assignment_count != 1)
    if bad_assignments.size:
        sample_index = int(selected[int(bad_assignments[0])])
        raise ValueError(
            (
                f'Hierarchy level {level} does not partition '
                f'cluster {view.node_id} exactly once; CSV '
                f'row {sample_index + 1} has assignment count '
                f'{int(assignment_count[int(bad_assignments[0])])}.'
            )
        )

    output_lines: list[str] = []
    filenames = data[PATH_COLUMN]
    for frontier_node, sample_indices in grouped_indices:
        output_lines.append(f"Cluster #{frontier_node}:")
        output_lines.extend(str(filenames.iloc[index])
            for index in sample_indices)

    hierarchy_text = "\n".join(output_lines) + "\n"
    record = {
        "stage": "cluster_export",
        "inputs": [Path(TREE_STATES_FILE), Path(TREE_TOPOLOGY_FILE)],
        "parents": [provenance_path(Path(TREE_STATES_FILE))],
        "producer": Path(__file__),
    }
    manifest = provenance_path(hierarchy_filename)
    if not publication_unchanged(
            manifest, {hierarchy_filename: hierarchy_text}, **record):
        write_text_atomically(hierarchy_filename, hierarchy_text)
        write_provenance(manifest, outputs=[hierarchy_filename], **record)

    print(
        f"Cluster {view.node_id} has {len(view.leaf_subclusters)} "
        "terminal subcluster(s)."
    )
    print(f"They are listed in file {cluster_filename}")
    print(
        (
            f'Hierarchy level {level} contains '
            f'{len(frontier)} frontier cluster(s).'
        )
    )
    print(f"Result written to file {hierarchy_filename}")


