def valid_cluster_range(topology: TreeTopology) -> range:
    """Return the valid immutable node-ID range."""
    return range(topology.node_count)


def _descendant_leaves(topology: TreeTopology, node: int) -> tuple[int, ...]:
    """Return a node's terminal descendants in deterministic order.

    Args:
        topology: Validated immutable topology.
        node: Permanent root of the requested subtree.

    Returns:
        Terminal node IDs in retained-child-first traversal order.
    """
    leaves: list[int] = []
    stack = [node]
    while stack:
        current = stack.pop()
        child_pair = topology.children.get(current)
        if child_pair is None:
            leaves.append(current)
            continue
        retained, extracted = child_pair
        stack.append(extracted)
        stack.append(retained)
    return tuple(leaves)


def _max_descendant_depth(topology: TreeTopology, node: int) -> int:
    """Return the maximum edge depth beneath a selected node.

    Args:
        topology: Validated immutable topology.
        node: Permanent root of the requested subtree.

    Returns:
        Maximum root-to-leaf edge count; zero for a terminal leaf.
    """
    maximum = 0
    stack = [(node, 0)]
    while stack:
        current, depth = stack.pop()
        maximum = max(maximum, depth)
        child_pair = topology.children.get(current)
        if child_pair is None:
            continue
        retained, extracted = child_pair
        stack.append((extracted, depth + 1))
        stack.append((retained, depth + 1))
    return maximum


def _frontier_at_level(
    topology: TreeTopology,
    node: int,
    level: int,
) -> tuple[int, ...]:
    """Return the complete frontier at a requested subtree depth.

    Args:
        topology: Validated immutable topology.
        node: Selected immutable subtree root.
        level: Nonnegative edge depth below the selected root.

    Returns:
        Partitioning node IDs; terminal leaves persist at deeper levels.

    Raises:
        ValueError: If ``level`` is negative.
    """
    if level < 0:
        raise ValueError("level must be non-negative.")

    frontier = [node]
    for _ in range(level):
        next_frontier: list[int] = []
        for current in frontier:
            child_pair = topology.children.get(current)
            if child_pair is None:
                next_frontier.append(current)
            else:
                next_frontier.extend(child_pair)
        frontier = next_frontier
    return tuple(frontier)


def build_cluster_view(
    data: pd.DataFrame,
    topology: TreeTopology,
    node_id: int,
) -> ClusterView:
    """Materialize membership and depth information for one node.

    Materialize membership and depth information for one immutable node.

    Args:
        data: Decoded immutable ``total_data.csv``.
        topology: Validated immutable tree topology.
        node_id: Permanent immutable node ID.

    Returns:
        A ``ClusterView`` describing the selected node.

    Raises:
        ValueError: If ``node_id`` is invalid, absent at its
            creation state, or its samples are not contiguous in the
            builder's sorted output.
    """
    cluster_range = valid_cluster_range(topology)
    if node_id not in cluster_range:
        raise ValueError(
            f"node_id {node_id} is out of range; valid immutable node "
            f"IDs are {cluster_range.start}..{cluster_range.stop - 1}."
        )

    states = data.iloc[:, 1:].to_numpy(dtype=np.int64, copy=False)
    creation_split = topology.creation_split[node_id]
    matching_indices = np.flatnonzero(states[:, creation_split] == node_id)

    if matching_indices.size == 0:
        raise ValueError(
            f"Immutable node {node_id} is absent from its creation state "
            f"{creation_split}."
        )

    start_index = int(matching_indices[0])
    end_index = int(matching_indices[-1]) + 1
    if len(matching_indices) != end_index - start_index:
        raise ValueError(
            (
                f"Cluster {node_id} rows are not contiguous "
                f"in total_data.csv; the immutable builder's "
                f"lexicographic-order contract is violated."
            )
        )

    leaf_subclusters = tuple(sorted(_descendant_leaves(topology, node_id)))
    return ClusterView(
        node_id=node_id,
        member_indices=matching_indices,
        max_level=_max_descendant_depth(topology, node_id),
        leaf_subclusters=leaf_subclusters,
    )


